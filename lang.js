// t('auth.wrong') / t('st.noDisk') -> teks sesuai bahasa aktif
function t(key, vars) {
    const lang = process.env.LANGUAGE || 'id';
    let s = (DICT[lang] && DICT[lang][key] !== undefined ? DICT[lang][key] : DICT.id[key]);
    if (s === undefined) s = key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => vars[k] != null ? vars[k] : m);
    return s;
}

t.DICT = DICT;
module.exports = t;
